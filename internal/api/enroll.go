package api

import "time"

// EnrollRequest is the body of POST /enroll (architecture §5.1, DH17), sent
// with the enrollment token as Bearer. The nonce makes the call idempotent: a
// retry with the same nonce returns the same device and re-delivers the
// escrowed key until the first heartbeat confirms it. Body cap MaxEnrollBody.
type EnrollRequest struct {
	Nonce         string      `json:"nonce"`          // 32 lowercase hex characters, generated by the installer
	Hostname      string      `json:"hostname"`       // 1..253 bytes, no path separators
	OS            string      `json:"os"`             // for example "windows"
	OSVersion     string      `json:"os_version"`     // free-form version text
	Arch          Arch        `json:"arch"`           // amd64, arm64 or x86
	DeviceClass   DeviceClass `json:"device_class"`   // laptop, desktop or unknown
	HWFingerprint string      `json:"hw_fingerprint"` // 16..128 lowercase hex characters
	AgentVersion  string      `json:"agent_version"`
	ResticVersion string      `json:"restic_version"`
}

// Validate checks the request. It returns nil or a *ValidationError.
func (r EnrollRequest) Validate() error {
	var c collector
	c.hexFixed("nonce", r.Nonce, 32)
	c.hostname("hostname", r.Hostname)
	c.text("os", r.OS, maxText, true)
	c.text("os_version", r.OSVersion, maxText, false)
	if !has(archs, r.Arch) {
		c.add("arch", msgUnknown)
	}
	if !has(deviceClass, r.DeviceClass) {
		c.add("device_class", msgUnknown)
	}
	c.hexRange("hw_fingerprint", r.HWFingerprint, 16, 128)
	c.text("agent_version", r.AgentVersion, maxText, true)
	c.text("restic_version", r.ResticVersion, maxText, true)
	return c.err()
}

// EnrollResponse is the body of the 200 answer of POST /enroll and the payload
// of an approved lobby request (architecture §5.1, DH17). It carries the only
// delivery of the device token, the gateway password and the repository
// password; each is a Secret. RepoPassword is empty when Custody is
// customer_held (DH22: the console never had it).
//
// CustomerID is the 26-character ULID of the customer the device belongs to. The
// agent needs it for the snapshot tag cb.customer=<customer_id> (architecture
// 6.3), which the protocol otherwise gave it no way to learn. It is an
// identifier, not a secret, and is not a Secret type.
//
// The Policy carries selection roots and exclude patterns, which are paths, but
// it flows console to agent only; AssertPathFree is run on what the console
// ingests, not on what it sends.
type EnrollResponse struct {
	DeviceID     string         `json:"device_id"`   // 26-character ULID
	CustomerID   string         `json:"customer_id"` // 26-character ULID; the snapshot tag cb.customer
	DeviceToken  Secret         `json:"device_token"`
	Gateway      Gateway        `json:"gateway"`
	RepoPassword Secret         `json:"repo_password,omitempty"`
	Custody      Custody        `json:"custody"`
	Policy       PolicyResponse `json:"policy"`
	ServerTime   time.Time      `json:"server_time"`
}

// Redacted returns a copy of r with every Secret blanked, safe for a log line.
func (r EnrollResponse) Redacted() EnrollResponse {
	r.DeviceToken = ""
	r.Gateway = r.Gateway.redacted()
	r.RepoPassword = ""
	r.Policy = r.Policy.Redacted()
	return r
}

// LobbyRequest is the body of POST /enroll/lobby (architecture §5.1): an
// install without a valid enrollment token asks to be approved by an operator.
// The route is anonymous and IP rate-limited; the body cap is MaxEnrollBody.
type LobbyRequest struct {
	Nonce         string `json:"nonce"` // 32 lowercase hex characters; also the secret of the poll URL
	Hostname      string `json:"hostname"`
	OS            string `json:"os"`
	Arch          Arch   `json:"arch"`
	HWFingerprint string `json:"hw_fingerprint"`
	AgentVersion  string `json:"agent_version"`
}

// Validate checks the request with the same rules as EnrollRequest.
func (r LobbyRequest) Validate() error {
	var c collector
	c.hexFixed("nonce", r.Nonce, 32)
	c.hostname("hostname", r.Hostname)
	c.text("os", r.OS, maxText, true)
	if !has(archs, r.Arch) {
		c.add("arch", msgUnknown)
	}
	c.hexRange("hw_fingerprint", r.HWFingerprint, 16, 128)
	c.text("agent_version", r.AgentVersion, maxText, true)
	return c.err()
}

// LobbyResponse is the body of POST /enroll/lobby (202, status pending, PollURL
// set) and of GET /enroll/lobby/{nonce} (architecture §5.1). When the request
// was approved the poll returns the enrollment payload once in Enroll.
// PollURL is a path on the same origin: RouteEnrollLobbyPoll(nonce).
type LobbyResponse struct {
	Status  LobbyStatus     `json:"status"`
	PollURL string          `json:"poll_url,omitempty"`
	Enroll  *EnrollResponse `json:"enroll,omitempty"`
}

// Redacted returns a copy of r with every Secret blanked (the nested
// EnrollResponse is copied, not shared).
func (r LobbyResponse) Redacted() LobbyResponse {
	if r.Enroll != nil {
		e := r.Enroll.Redacted()
		r.Enroll = &e
	}
	return r
}
