func TestRoots(t *testing.T) {
	tests := []struct {
		name string
		sel  Selection
		env  Environment
		want []string
	}{
		{"explicit roots are normalised, deduplicated and sorted",
			Selection{Roots: []string{`D:\Data\`, `C:\work`, `c:\WORK\`, `\\srv\share\dir\`, `C:\`}},
			Environment{}, []string{`\\srv\share\dir`, `C:\`, `C:\work`, `D:\Data`}}, // byte order: a backslash sorts before letters
		{"all_user_profiles", Selection{Presets: []string{PresetAllUserProfiles}},
			fixtureEnv, []string{`C:\Users\fixture`, `C:\Users\Fixture-Two`}},
		{"documents_desktop", Selection{Presets: []string{PresetDocumentsDesktop}},
			fixtureEnv, []string{`C:\Users\Fixture-Two\Desktop`, `C:\Users\Fixture-Two\Documents`, `C:\Users\fixture\Desktop`, `C:\Users\fixture\Documents`}}, // '-' sorts before a backslash
		{"fixed_drives accepts C, d: and E:\\", Selection{Presets: []string{PresetFixedDrives}},
			fixtureEnv, []string{`C:\`, `D:\`, `E:\`}},
		{"explicit spelling wins over a preset's, order does not matter",
			Selection{Roots: []string{`c:\users\FIXTURE`}, Presets: []string{PresetAllUserProfiles}},
			fixtureEnv, []string{`c:\users\FIXTURE`, `C:\Users\Fixture-Two`}},
		{"profile directory with a trailing backslash",
			Selection{Presets: []string{PresetDocumentsDesktop}},
			Environment{ProfileDirs: []string{`C:\Users\fixture\`}}, []string{`C:\Users\fixture\Desktop`, `C:\Users\fixture\Documents`}},
		{"two presets overlap and deduplicate",
			Selection{Presets: []string{PresetFixedDrives, PresetFixedDrives}},
			Environment{FixedDrives: []string{"c", "C:"}}, []string{`C:\`}},
		{"sorting is case-insensitive", Selection{Roots: []string{`C:\b`, `C:\A`, `C:\c`}},
			Environment{}, []string{`C:\A`, `C:\b`, `C:\c`}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Roots(tc.sel, tc.env)
			if err != nil {
				t.Fatalf("Roots: %v", err)
			}
			if !reflect.DeepEqual(got, tc.want) {
				t.Fatalf("got %q, want %q", got, tc.want)
			}
		})
	}
}

func TestRootsErrors(t *testing.T) {
	tests := []struct {
		name string
		sel  Selection
		env  Environment
		want string
	}{
		{"relative root", Selection{Roots: []string{`Documents`}}, Environment{}, "not an absolute Windows path"},
		{"forward slashes", Selection{Roots: []string{`C:/Data`}}, Environment{}, "not an absolute Windows path"},
		{"drive-relative", Selection{Roots: []string{`C:Data`}}, Environment{}, "not an absolute Windows path"},
		{"unix path", Selection{Roots: []string{`/home/x`}}, Environment{}, "not an absolute Windows path"},
		{"unc without share", Selection{Roots: []string{`\\server`}}, Environment{}, "not an absolute Windows path"},
		{"unknown preset", Selection{Presets: []string{"everything"}}, fixtureEnv, `unknown selection preset "everything"`},
		{"profiles preset without profiles", Selection{Presets: []string{PresetAllUserProfiles}}, Environment{}, "needs profile directories"},
		{"documents preset without profiles", Selection{Presets: []string{PresetDocumentsDesktop}}, Environment{}, "needs profile directories"},
		{"drives preset without drives", Selection{Presets: []string{PresetFixedDrives}}, Environment{}, "needs fixed drives"},
		{"bad drive", Selection{Presets: []string{PresetFixedDrives}}, Environment{FixedDrives: []string{"CD"}}, "not a drive letter"},
		{"bad profile directory", Selection{Presets: []string{PresetAllUserProfiles}}, Environment{ProfileDirs: []string{"Users"}}, "not an absolute Windows path"},
		{"nothing selected", Selection{}, fixtureEnv, "no roots"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Roots(tc.sel, tc.env)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("Roots = %q, %v; want error containing %q", got, err, tc.want)
			}
			if got != nil {
				t.Fatalf("an error must not come with a partial list, got %q", got)
			}
		})
	}
}

func golden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name)
	if os.Getenv("POLICY_UPDATE_GOLDEN") == "1" {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden %s: %v (regenerate with POLICY_UPDATE_GOLDEN=1)", path, err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s differs from the generated bytes.\n--- got ---\n%s\n--- want ---\n%s", name, got, want)
	}
}

