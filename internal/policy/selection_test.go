func TestExcludeFileProperties(t *testing.T) {
	sel := Selection{Excludes: []string{"@browser_caches", "@dev_caches", `*.tmp`, `~$*`, `!pagefile.sys`, `!C:\ProgramData\CryoBackup`}}
	out := ExcludeFile(sel, fixtureEnv)
	text := string(out)

	if bytes.ContainsRune(out, '\r') {
		t.Error("exclude file must use LF only")
	}
	if !strings.HasSuffix(text, "\n") {
		t.Error("exclude file must end with a newline")
	}
	if strings.Contains(text, "/") && !strings.Contains(text, "# ") {
		t.Error("unexpected forward slash")
	}
	for _, l := range strings.Split(strings.TrimSuffix(text, "\n"), "\n") {
		if strings.HasPrefix(l, "#") || l == "" {
			continue
		}
		if strings.ContainsRune(l, '/') {
			t.Errorf("pattern %q uses a forward slash; the decision is backslash", l)
		}
		if strings.Contains(strings.ReplaceAll(l, "$$", ""), "$") {
			t.Errorf("pattern %q has an unescaped $: restic would expand it as a variable", l)
		}
	}
	for _, want := range []string{`$$Recycle.Bin`, `~$$*`, `C:\Users\fixture\AppData\Local\Temp`, `C:\Users\Fixture-Two\AppData\Local\Temp`,
		`C:\Windows\Temp`, `C:\ProgramData\CryoBackup`} {
		if !strings.Contains(text, want+"\n") {
			t.Errorf("missing line %q", want)
		}
	}

	lines := strings.Split(text, "\n")
	lastIndex := func(l string) int {
		idx := -1
		for i, x := range lines {
			if x == l {
				idx = i
			}
		}
		return idx
	}
	firstIndex := func(l string) int {
		for i, x := range lines {
			if x == l {
				return i
			}
		}
		return -1
	}
	reinclude := lastIndex("!pagefile.sys")
	if reinclude < 0 {
		t.Fatal("custom re-include line missing")
	}
	for _, m := range MandatoryExcludes(fixtureEnv) {
		line := strings.ReplaceAll(m, "$", "$$")
		if firstIndex(line) < 0 {
			t.Errorf("mandatory %q missing", m)
		}
		if lastIndex(line) <= reinclude {
			t.Errorf("mandatory %q is not repeated after the custom re-includes; restic's last match wins", m)
		}
	}

	// Without a re-include the mandatory block is written exactly once.
	plain := string(ExcludeFile(Selection{Excludes: []string{`*.tmp`}}, fixtureEnv))
	if n := strings.Count(plain, "\npagefile.sys\n"); n != 1 {
		t.Errorf("pagefile.sys appears %d times without a re-include, want 1", n)
	}
	if strings.Contains(plain, "mandatory again") {
		t.Error("the enforcement block must only appear when a custom line re-includes")
	}
}

func TestExcludeFileDeterministicAndPure(t *testing.T) {
	sel := Selection{Excludes: []string{"@installers", "*.x"}}
	a := ExcludeFile(sel, fixtureEnv)
	b := ExcludeFile(sel, fixtureEnv)
	if !bytes.Equal(a, b) {
		t.Fatal("ExcludeFile is not deterministic")
	}
	if sel.Excludes[0] != "@installers" || len(sel.Excludes) != 2 {
		t.Fatal("ExcludeFile modified its input")
	}
}

func TestExcludeFileGlobMetacharactersInProfileDir(t *testing.T) {
	env := Environment{SystemDrive: "C:", ProfileDirs: []string{`C:\Users\a[1]`}}
	text := string(ExcludeFile(Selection{}, env))
	if !strings.Contains(text, "C:\\Users\\a[[]1]\\AppData\\Local\\Temp\n") {
		t.Errorf("a '[' in a profile directory must be neutralised with [[]:\n%s", text)
	}
}

func TestMandatoryExcludes(t *testing.T) {
	got := MandatoryExcludes(Environment{})
	want := []string{`C:\ProgramData\CryoBackup`, `pagefile.sys`, `hiberfil.sys`, `swapfile.sys`, `DumpStack.log.tmp`, `$Recycle.Bin`, `System Volume Information`}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("defaults: got %q, want %q", got, want)
	}
	got = MandatoryExcludes(Environment{SystemDrive: "D:", ProgramData: `E:\PD\`, ProfileDirs: []string{`D:\Users\u`, "bad"}})
	want = []string{`E:\PD\CryoBackup`, `D:\Users\u\AppData\Local\restic`, `pagefile.sys`, `hiberfil.sys`, `swapfile.sys`, `DumpStack.log.tmp`, `$Recycle.Bin`, `System Volume Information`}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("custom: got %q, want %q", got, want)
	}
	if got := MandatoryExcludes(Environment{SystemDrive: "D:"})[0]; got != `D:\ProgramData\CryoBackup` {
		t.Fatalf("ProgramData must default under the system drive, got %q", got)
	}
}

func TestBaselineAndPresetsAreWellFormed(t *testing.T) {
	check := func(name string, list []string) {
		if len(list) == 0 {
			t.Errorf("%s is empty", name)
		}
		for _, e := range list {
			switch {
			case e == "" || strings.HasPrefix(e, "#") || strings.HasPrefix(e, "!"):
				t.Errorf("%s entry %q must be a plain pattern", name, e)
			case strings.Contains(e, "/"):
				t.Errorf("%s entry %q uses a forward slash", name, e)
			case strings.Contains(e, "%") && !strings.HasPrefix(e, TokenProfile+`\`) && !strings.HasPrefix(e, TokenSystemDrive+`\`):
				t.Errorf("%s entry %q has a misplaced token", name, e)
			}
		}
	}
	check("Baseline", Baseline)
	wantPresets := []string{"browser_caches", "dev_caches", "installers", "vm_images"}
	if got := exclusionPresetNames(); !reflect.DeepEqual(got, wantPresets) {
		t.Fatalf("exclusion presets = %q, want %q", got, wantPresets)
	}
	for name, list := range ExclusionPresets {
		check("preset "+name, list)
	}
	// The baseline must carry everything architecture §3.6 and matrix r50 name.
	need := []string{`AppData\Local\Temp`, `AppData\Local\Microsoft\WindowsApps`, `Windows\Temp`, `$Recycle.Bin`, `pagefile.sys`, `hiberfil.sys`, `swapfile.sys`,
		`System Volume Information`, `Chrome`, `Edge`, `Firefox`, `Prefetch`, `thumbcache_*.db`}
	joined := strings.Join(Baseline, "\n")
	for _, n := range need {
		if !strings.Contains(joined, n) {
			t.Errorf("Baseline lacks %q", n)
		}
	}
	for _, e := range ExclusionPresets["dev_caches"] {
		if strings.Contains(strings.ToLower(e), ".git") && !strings.Contains(e, ".gitignore") {
			if strings.HasSuffix(strings.ToLower(e), `.git`) || strings.Contains(strings.ToLower(e), `\.git\`) {
				t.Errorf("dev_caches must not exclude .git: %q", e)
			}
		}
	}
}
